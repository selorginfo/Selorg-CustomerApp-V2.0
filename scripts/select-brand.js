/**
 * Activates one brand x one environment for the next Metro run.
 *
 *   node scripts/select-brand.js selorg development
 *   node scripts/select-brand.js sodakku production
 *   node scripts/select-brand.js --if-missing        # seed the brand file only
 *
 * Selorg writes src/brands/active.generated.ts and `.env`, exactly as before. `.env` source,
 * first match wins:
 *   env/selorg/.env.<mode>
 *   env/_shared/.env.<mode>
 *   .env.<mode>
 * Refuses to overwrite a `.env` that matches no source file unless `--force`.
 *
 * A partner brand never writes `.env`. It resolves env/<brand>/.env.<mode> (see brand-env.js)
 * into env/<brand>/.env.resolved, and refuses — leaving the active brand unchanged — when a
 * required key is missing, blank, or still points at Selorg.
 */
const fs = require('fs');
const path = require('path');
const brandEnv = require('./brand-env');

const ROOT = path.join(__dirname, '..');
const BRANDS_DIR = path.join(ROOT, 'src', 'brands');
const GENERATED = path.join(BRANDS_DIR, 'active.generated.ts');
const ENV_ROOT = path.join(ROOT, 'env');

const DEFAULT_BRAND = 'selorg';
const DEFAULT_MODE = 'development';
const MODES = ['development', 'qa', 'staging', 'production'];

const ifMissing = process.argv.includes('--if-missing');
const args = process.argv.slice(2).filter(a => !a.startsWith('--'));
const rel = p => path.relative(ROOT, p);

function writeGenerated(brand, mode) {
  fs.writeFileSync(
    GENERATED,
    '// AUTO-GENERATED by scripts/select-brand.js - do not edit, do not commit.\n' +
      `export const ACTIVE_BRAND_KEY = '${brand}';\n` +
      `export const ACTIVE_BRAND_ENV = '${mode}';\n` +
      `export { default as ACTIVE_BRAND_MODULE } from './${brand}';\n`,
  );
}

if (ifMissing) {
  const old = fs.existsSync(GENERATED) ? fs.readFileSync(GENERATED, 'utf8') : '';
  // Older generated files lack ACTIVE_BRAND_MODULE; upgrade them, keeping their brand.
  if (!old.includes('ACTIVE_BRAND_MODULE')) {
    const keep = (re, fallback) => (re.exec(old) || [])[1] || fallback;
    const seedBrand = keep(/ACTIVE_BRAND_KEY = '([^']+)'/, DEFAULT_BRAND);
    const seedMode = keep(/ACTIVE_BRAND_ENV = '([^']+)'/, DEFAULT_MODE);
    writeGenerated(seedBrand, seedMode);
    console.log(`[brand] seeded ${rel(GENERATED)} with brand=${seedBrand}`);
  }
  process.exit(0);
}

const brand = args[0] || process.env.SELORG_BRAND || DEFAULT_BRAND;
const mode = args[1] || process.env.SELORG_ENV || DEFAULT_MODE;

const known = fs
  .readdirSync(BRANDS_DIR, { withFileTypes: true })
  .filter(d => d.isDirectory())
  .map(d => d.name);
if (!known.includes(brand)) {
  console.error(`[brand] Unknown brand "${brand}". Known: ${known.join(', ')}`);
  process.exit(1);
}
if (!MODES.includes(mode)) {
  console.error(`[brand] Unknown mode "${mode}". Known: ${MODES.join(', ')}`);
  process.exit(1);
}

if (brand !== DEFAULT_BRAND) {
  const partnerFile = path.join(ENV_ROOT, brand, `.env.${mode}`);
  const result = brandEnv.resolvePartnerEnv({
    brand,
    mode,
    partner: brandEnv.readEnvFile(partnerFile),
    selorg: brandEnv.readEnvFile(path.join(ROOT, '.env')),
  });
  if (result.errors.length) {
    console.error(`[brand] ${brand}/${mode} is not usable (${rel(partnerFile)}); active brand unchanged:`);
    result.errors.forEach(e => console.error(`  - ${e}`));
    process.exit(1);
  }
  const out = brandEnv.resolvedPath(ROOT, brand);
  fs.writeFileSync(out, brandEnv.serialize(result.values));
  writeGenerated(brand, mode);
  console.log(`[brand] brand=${brand} mode=${mode}`);
  console.log(`[brand] ${rel(out)} <- ${rel(partnerFile)} (root .env untouched)`);
  if (result.inherited.length) console.log(`[brand] inherited from Selorg (brand-neutral): ${result.inherited.join(', ')}`);
  console.log('[brand] restart Metro with --reset-cache to pick up the change');
  process.exit(0);
}

const candidates = [
  path.join(ENV_ROOT, brand, `.env.${mode}`),
  path.join(ENV_ROOT, '_shared', `.env.${mode}`),
];
if (brand === DEFAULT_BRAND) candidates.push(path.join(ROOT, `.env.${mode}`));

const src = candidates.find(c => fs.existsSync(c));
if (!src) {
  console.error(
    `[brand] No env file for ${brand}/${mode}. Looked in:\n  ${candidates.map(rel).join('\n  ')}`,
  );
  process.exit(1);
}

/** Parsed KEY=value pairs; values are only ever inspected, never printed. */
function parseEnv(file) {
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (m) out[m[1]] = m[2].trim().replace(/^['"]|['"]$/g, '');
  }
  return out;
}

const srcEnv = parseEnv(src);
const srcBrand = srcEnv.BRAND_KEY || '';
if (srcBrand ? srcBrand !== brand : brand !== DEFAULT_BRAND) {
  console.error(
    `[brand] ${rel(src)} declares BRAND_KEY="${srcBrand}" but brand "${brand}" was requested. ` +
      'Partner env files must set BRAND_KEY to their own brand.',
  );
  process.exit(1);
}

// A hand-edited live .env matches no source file; overwriting it would lose it.
function knownEnvSources() {
  const files = MODES.map(m => path.join(ROOT, `.env.${m}`));
  if (fs.existsSync(ENV_ROOT)) {
    for (const dir of fs.readdirSync(ENV_ROOT, { withFileTypes: true })) {
      if (!dir.isDirectory()) continue;
      for (const m of MODES) files.push(path.join(ENV_ROOT, dir.name, `.env.${m}`));
    }
  }
  return files.filter(f => fs.existsSync(f));
}
const DOTENV = path.join(ROOT, '.env');
if (fs.existsSync(DOTENV) && !process.argv.includes('--force')) {
  const live = fs.readFileSync(DOTENV);
  if (!knownEnvSources().some(f => fs.readFileSync(f).equals(live))) {
    console.error(
      '[brand] .env does not match any env source file, so it may hold unsaved edits.\n' +
        '[brand] Save it as the right .env.<mode> file, or re-run with --force to overwrite it.',
    );
    process.exit(1);
  }
}

writeGenerated(brand, mode);
fs.copyFileSync(src, DOTENV);

console.log(`[brand] brand=${brand} mode=${mode}`);
console.log(`[brand] .env <- ${rel(src)}`);
console.log('[brand] restart Metro with --reset-cache to pick up the change');
