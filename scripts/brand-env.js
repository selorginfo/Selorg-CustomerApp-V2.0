/**
 * Brand-aware env resolution shared by select-brand.js and babel.config.js.
 *
 * Selorg keeps reading the root `.env`, untouched. A partner brand reads
 * `env/<brand>/.env.<mode>` and the result is written to `env/<brand>/.env.resolved`
 * (gitignored); the root `.env` is never written for a partner.
 *
 * A partner only inherits a Selorg value for names in SPEC.shareable. Customer API
 * origins must be the partner's own host. Maps keys and the payment API are shared
 * with Selorg. Everything else must come from the partner file.
 * Errors name keys only, never values.
 */
const fs = require('fs');
const path = require('path');

const DEFAULT_BRAND = 'selorg';
const MODES = ['development', 'qa', 'staging', 'production'];

const SPEC = {
  /**
   * Taken from Selorg when the partner file leaves them blank. Maps and the payment
   * API stay on Selorg; the customer API host does not.
   */
  shareable: [
    'APP_MODE',
    'APP_ENV',
    'PAYMENT_STANDALONE_MODE',
    'PAYMENT_API_BASE_URL',
    'GOOGLE_MAPS_API_KEY',
    'EXPO_PUBLIC_GOOGLE_MAPS_API_KEY',
  ],
  /** Per mode, at least one name of each group must be set (src/config/api.ts reads them in this order). */
  requiredAnyOf: {
    production: [['PROD_API_BASE_URL', 'API_BASE_URL']],
    default: [['DEV_API_BASE_URL', 'API_BASE_URL']],
  },
  /** Customer API origins must not equal Selorg's. Maps and payment are shareable. */
  brandSpecific: ['API_BASE_URL', 'DEV_API_BASE_URL', 'PROD_API_BASE_URL', 'EAS_PROJECT_ID'],
  /** Customer API origins that must never point at a Selorg host. Payment may. */
  hostKeys: ['API_BASE_URL', 'DEV_API_BASE_URL', 'PROD_API_BASE_URL'],
  /** Customer API origins that must be public https in a production build. */
  productionHostKeys: ['API_BASE_URL', 'PROD_API_BASE_URL'],
};

const SELORG_HOST = /(^|[./@])selorg\.(com|in)(?=$|[/:?#])/i;
const LOOPBACK = /^https?:\/\/(localhost|127\.|10\.|192\.168\.|0\.0\.0\.0|\[::1\])/i;

function parseEnv(text) {
  const out = {};
  for (const line of String(text).split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let v = m[2].trim();
    if (/^(['"]).*\1$/.test(v)) v = v.slice(1, -1);
    else v = v.replace(/\s+#.*$/, '');
    out[m[1]] = v;
  }
  return out;
}

function readEnvFile(file) {
  return fs.existsSync(file) ? parseEnv(fs.readFileSync(file, 'utf8')) : null;
}

function hostOf(value) {
  try {
    return new URL(value).hostname;
  } catch {
    return value;
  }
}

/**
 * @param {{brand: string, mode: string, partner: Record<string,string>|null, selorg: Record<string,string>|null, spec?: typeof SPEC}} input
 * @returns {{values: Record<string,string>, inherited: string[], errors: string[]}}
 */
function resolvePartnerEnv({ brand, mode, partner, selorg, spec = SPEC }) {
  const values = {};
  const inherited = [];
  const errors = [];
  if (!partner) {
    return { values, inherited, errors: [`No env file for ${brand}/${mode}; nothing is inherited from Selorg.`] };
  }
  for (const [k, v] of Object.entries(partner)) if (String(v).trim() !== '') values[k] = String(v).trim();
  const base = selorg || {};
  for (const k of spec.shareable) {
    if (!(k in values) && String(base[k] ?? '').trim() !== '') {
      values[k] = String(base[k]).trim();
      inherited.push(k);
    }
  }
  if (values.BRAND_KEY !== brand) errors.push(`BRAND_KEY must be "${brand}".`);
  const groups = spec.requiredAnyOf[mode] || spec.requiredAnyOf.default || [];
  for (const group of groups) {
    if (!group.some(k => values[k])) errors.push(`${group.join(' or ')} is required for ${brand} (${mode}) and is missing or empty.`);
  }
  for (const k of spec.brandSpecific) {
    if (values[k] && String(base[k] ?? '').trim() === values[k]) errors.push(`${k} reuses the Selorg value; ${brand} needs its own.`);
  }
  for (const k of spec.hostKeys) {
    if (values[k] && SELORG_HOST.test(hostOf(values[k]))) errors.push(`${k} points at a Selorg host.`);
  }
  if (mode === 'production') {
    for (const k of spec.productionHostKeys) {
      if (!values[k]) continue;
      if (!/^https:\/\//i.test(values[k]) || LOOPBACK.test(values[k])) errors.push(`${k} must be a public https URL in production.`);
    }
    if (values.APP_MODE && values.APP_MODE.toLowerCase() !== 'production') errors.push('APP_MODE must be "production" in a production build.');
  }
  return { values, inherited, errors };
}

function serialize(values) {
  return (
    '# AUTO-GENERATED by scripts/select-brand.js from env/<brand>/.env.<mode> - do not edit, do not commit.\n' +
    Object.entries(values)
      .map(([k, v]) => `${k}=${/[\s#"']/.test(v) ? JSON.stringify(v) : v}`)
      .join('\n') +
    '\n'
  );
}

function readActiveBrand(root) {
  const generated = path.join(root, 'src', 'brands', 'active.generated.ts');
  if (!fs.existsSync(generated)) return DEFAULT_BRAND;
  return (/ACTIVE_BRAND_KEY\s*=\s*'([^']+)'/.exec(fs.readFileSync(generated, 'utf8')) || [])[1] || DEFAULT_BRAND;
}

const resolvedPath = (root, brand) => path.join(root, 'env', brand, '.env.resolved');

/** The dotenv file Babel should inline for the active brand. Throws for a partner that was never resolved. */
function activeDotenvPath(root) {
  const brand = readActiveBrand(root);
  if (brand === DEFAULT_BRAND) return path.join(root, '.env');
  const file = resolvedPath(root, brand);
  if (!fs.existsSync(file)) {
    throw new Error(`[brand] ${brand} is active but env/${brand}/.env.resolved is missing. Run: npm run brand -- ${brand} <mode>`);
  }
  return file;
}

module.exports = {
  DEFAULT_BRAND,
  MODES,
  SPEC,
  parseEnv,
  readEnvFile,
  resolvePartnerEnv,
  serialize,
  readActiveBrand,
  resolvedPath,
  activeDotenvPath,
};
